    def test_postgres_copy_roundtrip_preserves_null_empty_and_rejections(self):
        with psycopg.connect(DSN) as conn:
            for table in ("copy_source", "copy_target"):
                constraint = "CHECK (id > 0)" if table == "copy_target" else ""
                conn.execute(sql.SQL("CREATE TABLE {}.{} (id integer {}, first text, second text)")
                             .format(sql.Identifier(self.schema), sql.Identifier(table), sql.SQL(constraint)))
            conn.execute(sql.SQL("INSERT INTO {}.copy_source VALUES (%s,%s,%s),(%s,%s,%s),(%s,%s,%s),(%s,%s,%s),(%s,%s,%s)")
                         .format(sql.Identifier(self.schema)),
                         (1, None, "", 2, "", None, 3, " ", 'a; "quote"\nnext', 4, None, None, -1, None, ""))
        source = Path(self.directory.name) / "postgres-copy.csv"
        with psycopg.connect(DSN) as conn:
            with conn.cursor().copy(sql.SQL("COPY (SELECT id, first, second FROM {}.copy_source ORDER BY id) TO STDOUT WITH (FORMAT CSV, HEADER, DELIMITER ';')")
                                    .format(sql.Identifier(self.schema))) as copy, source.open("wb") as target:
                for chunk in copy:
                    target.write(chunk)
        report = Path(self.directory.name) / "copy-rejected.csv"
        base = [sys.executable, "-m", "scripts.cli"]
        common = [str(source), "--schema", self.schema, "--table", "copy_target", "--dsn", DSN,
                  "--delimiter", ";", "--postgres-csv"]
        preview = subprocess.run([*base, "preview", str(source), "--delimiter", ";", "--postgres-csv", "--limit", "1"],
                                 cwd=ROOT, capture_output=True, text=True)
        self.assertEqual(preview.returncode, 0, preview.stderr)
        self.assertIn('[-1,', preview.stdout.replace('"-1"', '-1'))
        self.assertIn('null, ""', preview.stdout)
        validation = subprocess.run([*base, "validate", *common], cwd=ROOT, capture_output=True, text=True)
        self.assertEqual(validation.returncode, 0, validation.stderr)
        dry = subprocess.run([*base, *common, "--rejects", str(report), "--dry-run"],
                             cwd=ROOT, capture_output=True, text=True)
        self.assertEqual(dry.returncode, 0, dry.stderr)
        with psycopg.connect(DSN) as conn:
            self.assertEqual(conn.execute(sql.SQL("SELECT count(*) FROM {}.copy_target").format(sql.Identifier(self.schema))).fetchone()[0], 0)
        result = subprocess.run([*base, *common, "--rejects", str(report)], cwd=ROOT, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("Rows saved: 4. Rows rejected: 1.", result.stdout)
        with psycopg.connect(DSN) as conn:
            mismatches = conn.execute(sql.SQL("SELECT count(*) FROM {}.copy_source s JOIN {}.copy_target t USING (id) WHERE s.first IS DISTINCT FROM t.first OR s.second IS DISTINCT FROM t.second")
                                      .format(sql.Identifier(self.schema), sql.Identifier(self.schema))).fetchone()[0]
        self.assertEqual(mismatches, 0)
        with report.open(encoding="utf-8", newline="") as f:
            rejected = list(csv.DictReader(f))
        self.assertEqual(len(rejected), 1)
        from scripts.cli import read_csv
        with read_csv(report, postgres_csv=True) as (_, rows):
            self.assertEqual(list(rows)[0][:3], ["'-1", None, ""])
        report.write_text(report.read_text(encoding="utf-8").replace("\"'-1\",", '"5",', 1), encoding="utf-8")
        retry_report = Path(self.directory.name) / "postgres-retry.csv"
        retried = subprocess.run([*base, "retry", str(report), "--schema", self.schema, "--table", "copy_target",
                                  "--dsn", DSN, "--postgres-csv", "--rejects", str(retry_report)],
                                 cwd=ROOT, capture_output=True, text=True)
        self.assertEqual(retried.returncode, 0, retried.stderr)
        with psycopg.connect(DSN) as conn:
            values = conn.execute(sql.SQL("SELECT first, second FROM {}.copy_target WHERE id = 5")
                                  .format(sql.Identifier(self.schema))).fetchone()
        self.assertEqual(values, (None, ""))

    def test_correct_report_and_retry_into_database(self):
        source = Path(self.directory.name) / "original.csv"
        source.write_text('address,price,rooms\nValid,10,1\n"Bad, Street",wrong,2\nMissing,20\nExtra,30,3,unexpected\n', encoding="utf-8")
        result, report = self.run_cli(source)
        self.assertEqual(result.returncode, 0, result.stderr)
        with report.open(encoding="utf-8", newline="") as f:
            reader = csv.DictReader(f)
            headers = reader.fieldnames
            rows = list(reader)
        self.assertEqual(len(rows), 3)
        self.assertEqual(rows[0]["address"], "Bad, Street")
        self.assertEqual(rows[1]["rowport_record"], "4")
        self.assertEqual(json.loads(rows[2]["rowport_extra"]), ["unexpected"])
        rows[0]["price"] = "40"
        rows[1]["rooms"] = "2"
        with report.open("w", encoding="utf-8", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=headers)
            writer.writeheader()
            writer.writerows(rows)
        failed_report = Path(self.directory.name) / "failed-retry.csv"
        failed = subprocess.run([sys.executable, "-m", "scripts.cli", "retry", str(report), "--dsn", DSN,
                                 "--schema", self.schema, "--table", "properties", "--rejects", str(failed_report)],
                                cwd=ROOT, capture_output=True, text=True)
        self.assertNotEqual(failed.returncode, 0)
        self.assertIn("extra fields", failed.stderr)
        self.assertEqual(self.count(), 1)
        self.assertFalse(failed_report.exists())
        rows[2]["rowport_extra"] = ""
        with report.open("w", encoding="utf-8", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=headers)
            writer.writeheader()
            writer.writerows(rows)
        next_report = Path(self.directory.name) / "retry-rejects.csv"
        result = subprocess.run([sys.executable, "-m", "scripts.cli", "retry", str(report),
                                 "--dsn", DSN, "--schema", self.schema, "--table", "properties",
                                 "--rejects", str(next_report)], cwd=ROOT, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("Rows saved: 3. Rows rejected: 0.", result.stdout)
        self.assertEqual(self.count(), 4)
        with next_report.open(encoding="utf-8", newline="") as f:
            self.assertEqual(list(csv.DictReader(f)), [])

    def test_formula_safe_report_retry_restores_original_values(self):
        with psycopg.connect(DSN) as conn:
            conn.execute(sql.SQL('CREATE TABLE {}.formula_target ("=name" text, amount integer)').format(sql.Identifier(self.schema)))
        source = Path(self.directory.name) / "formula.csv"
        values = ["=1+2", "+SUM(1,2)", "-42", "@name", "  =1+2", "'=literal", "'normal", "normal", "\tvalue"]
        with source.open("w", encoding="utf-8", newline="") as f:
            writer = csv.writer(f)
            writer.writerow(["=name", "amount"])
            writer.writerows((value, "bad") for value in values)
        report = Path(self.directory.name) / "formula-rejects.csv"
        common = ["--dsn", DSN, "--schema", self.schema, "--table", "formula_target"]
        initial = subprocess.run([sys.executable, "-m", "scripts.cli", str(source), *common, "--rejects", str(report)],
                                 cwd=ROOT, capture_output=True, text=True)
        self.assertEqual(initial.returncode, 0, initial.stderr)
        with report.open(encoding="utf-8", newline="") as f:
            reader = csv.DictReader(f)
            fields, rows = reader.fieldnames, list(reader)
        self.assertEqual(fields[0], "'=name")
        self.assertEqual(len(rows), len(values))
        self.assertTrue(all(row["'=name"].startswith("'") for row in rows[:-2]))
        for row in rows:
            row["amount"] = "10"
        with report.open("w", encoding="utf-8", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=fields)
            writer.writeheader()
            writer.writerows(rows)
        retry = subprocess.run([sys.executable, "-m", "scripts.cli", "retry", str(report), *common,
                                "--rejects", str(Path(self.directory.name) / "again.csv")],
                               cwd=ROOT, capture_output=True, text=True)
        self.assertEqual(retry.returncode, 0, retry.stderr)
        with psycopg.connect(DSN) as conn:
            saved = conn.execute(sql.SQL('SELECT "=name" FROM {}.formula_target ORDER BY ctid').format(sql.Identifier(self.schema))).fetchall()
        self.assertEqual([row[0] for row in saved], values)

